CREATE TABLE IF NOT EXISTS "MusicTrack" (
"id" TEXT NOT NULL,
"videoId" TEXT NOT NULL,
"name" TEXT,
"audioUrl" TEXT NOT NULL,
"duration" DOUBLE PRECISION NOT NULL,
"startTime" DOUBLE PRECISION NOT NULL DEFAULT 0,
"trimStart" DOUBLE PRECISION NOT NULL DEFAULT 0,
"trimEnd" DOUBLE PRECISION NOT NULL DEFAULT 0,
"volume" DOUBLE PRECISION NOT NULL DEFAULT 1,
"muted" BOOLEAN NOT NULL DEFAULT FALSE,
"createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT "MusicTrack_pkey" PRIMARY KEY ("id"),
CONSTRAINT "MusicTrack_videoId_fkey"
FOREIGN KEY ("videoId") REFERENCES "Video"("id")
ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS "MusicTrack_videoId_idx"
ON "MusicTrack"("videoId");
